// Build-time only (uses Ajv code generation): the source of the committed reader validator.
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneModule from "ajv/dist/standalone/index.js";
import { readerSchema } from "../src/check.ts";

// CommonJS module whose typing says namespace; under NodeNext the default import is the function.
const standaloneCode = standaloneModule as unknown as (ajv: Ajv2020, validate: unknown) => string;

const HEADER = `// GENERATED by scripts/build-reader-validator.ts from readerSchema(class.schema.json). Do not edit.
// Run \`npm run build:reader\` in schema/ts after a schema change; a test fails when this is stale.
// @ts-nocheck
import func1 from "./ucs2length.ts";
`;

/** The generated module's text for a class schema (Ajv standalone code, ES module). */
export function readerValidatorSource(classSchema: unknown): string {
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
  let code = standaloneCode(ajv, ajv.compile(readerSchema(classSchema)));
  code = code.replace(/^"use strict";/, "");
  // The only runtime helper the schema needs is ucs2length; swap its CommonJS require for an import.
  const helper = 'const func1 = require("ajv/dist/runtime/ucs2length").default;';
  if (!code.includes(helper)) throw new Error("expected the ucs2length require in the generated code");
  code = code.replace(helper, "");
  if (/\brequire\(|new Function|\beval\(/.test(code)) throw new Error("generated code still needs run-time code generation");
  return HEADER + code + "\n";
}
