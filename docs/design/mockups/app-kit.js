// Building blocks of the Android app's own screens (docs/design/app.md and the app-*.md specs).
// Pure string functions, no I/O. The full-screen pages are the rider page's pages (rider-kit.js,
// companion.css): the same type, keys and plates, so the app's screens and the phone pages read
// as one family. The class itself is the /play room screen (play-kit.js) with the app's band.
// Every piece of text is a leaf with data-tier, so measure.js checks it.
'use strict';

const R = require('./rider-kit');
const P = require('./play-kit');

const { esc, T, key, page, h1, p, field, plate } = R;

// Who draws a screen: native (Kotlin, Android views with the same tokens and bundled fonts) or the
// web view. The mock-up says so in a data attribute only; nothing on the screen shows it.
const native = (body) => body.replace('<main class="page', '<main data-layer="native" class="page');

// The mode strip: the one way between the two modes, on each mode's start page only.
// lead: a line above the key (grey). The key names the mode it goes to.
const strip = (label, lead = '') => `<nav class="strip" aria-label="Mode">${lead ? T('label', lead, 3, ' class="sl"') : ''}`
  + `${key('switch_mode', label, { full: true })}</nav>`;

// The mode tag at the top of a start page: which mode the app is in, in words.
const mode = (name) => `<p class="mode">${T('label', name, 1)}</p>`;

// The pairing code: typed on another device, read at arm's length. Value tier, digits in cells.
const code = (c, o = {}) => `<div class="pcode${o.dim ? ' dim' : ''}" aria-label="Pairing code">${T('label', 'Code', 1, ' class="lab"')}`
  + `<span class="v n" data-tier="value">${esc(c)}</span></div>`;

// Numbered steps. items: strings.
const steps = (items) => `<ol class="steps">${items.map((s, i) => `<li><span class="sn n" data-tier="minor">${i + 1}</span>${T('label', s, 4, ' class="st"')}</li>`).join('')}</ol>`;

// A status line with the "working" marker (a hollow circle): something is going on.
const work = (text, lines = 2) => `<div class="work" role="status">${T('minor', text, lines)}</div>`;

// A grey note with the square marker: a choice or a fact, not a fault.
const note = (text, lines = 4) => `<p class="anote">${T('label', text, lines)}</p>`;

// Two keys side by side (the main one last, at the right) or one alone.
const duo = (...ks) => `<div class="duo${ks.length === 1 ? ' solo' : ''}">${ks.join('')}</div>`;
// Two keys stacked: for a choice whose words are long.
const stack = (...ks) => `<div class="stack">${ks.join('')}</div>`;

// The app's band on the class screen: play.md's band, plus "Follow the music" while the clock is
// manual and the music could be followed (app-follow.md). kind: start, pause, resume.
const btn = (action, word, sub, cls = '') => `<button class="btn${cls ? ' ' + cls : ''}" data-action="${action}"><span class="w" data-tier="label">${esc(word)}</span>${sub ? `<span class="sub" data-tier="label">${esc(sub)}</span>` : ''}</button>`;
function band(kind, o = {}) {
  const main = { start: 'Start', pause: 'Pause', resume: 'Resume' }[kind];
  const follow = o.follow ? btn('follow', 'Follow', 'The music', 'follow') : '';
  return `<nav class="controls" aria-label="Class controls">${follow}<div class="transport">${btn('previous', 'Previous', 'Interval')}`
    + `${btn(kind, main, '', 'main')}${btn('next', 'Next', 'Interval')}</div>${btn('end', 'End', '', 'quit')}</nav>`;
}

const SHEET = (spec) => `Spec: docs/design/${spec}. Generated by app-pages.js: edit that, not this file.`;

// A full-screen page of the app (native or web view). spec: the spec file it belongs to.
function doc(title, comment, spec, body) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(title)}</title>
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="companion.css">
<link rel="stylesheet" href="rider.css">
<link rel="stylesheet" href="app.css">
</head>
<body class="app">
<!-- ${comment}  ${SHEET(spec)} -->
${body}
</body>
</html>
`;
}

// The class screen of the app (the /play room screen with the app's band). shown: the band shows.
function roomDoc(title, comment, spec, body, shown) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(title)}</title>
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="room.css">
<link rel="stylesheet" href="controls.css">
<link rel="stylesheet" href="play.css">
<link rel="stylesheet" href="app-room.css">
</head>
<body class="play app-room${shown ? ' shown' : ''}">
<!-- ${comment}  ${SHEET(spec)} -->
${body}
</body>
</html>
`;
}

module.exports = { esc, T, key, page, h1, p, field, plate, native, strip, mode, code, steps, work, note, duo, stack, band, doc, roomDoc, R, P };
