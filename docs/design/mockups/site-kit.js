// Building blocks of the website mock-ups (docs/design/site.md). Pure string functions: no I/O.
// Every piece of text is a leaf span with data-tier and data-min-cap, so measure.js can check it
// (cap height in pixels at the smallest size the text is set in, contrast, collisions, cut-off).
'use strict';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// kind: [tier, minimum cap height in px]. The size each kind is set in is in site.css; the
// minimum is for the smallest size (phone) and is about 0.68 of the font size.
const KIND = {
  brand: ['minor', 17], h1: ['minor', 21], h2: ['minor', 17], body: ['minor', 12], strong: ['minor', 12],
  title: ['minor', 13], small: ['minor', 10], label: ['label', 9], btn: ['minor', 12], len: ['minor', 17],
  code: ['minor', 26], zn: ['minor', 17], flab: ['minor', 10],
};

// A text leaf. lines: how many lines it may take before the checker calls it a problem.
function T(kind, text, lines = 6) {
  const [tier, min] = KIND[kind];
  return `<span data-tier="${tier}" data-min-cap="${min}" data-lines="${lines}">${esc(text)}</span>`;
}

const h1 = (text, count) => `<h1>${T('h1', text, 3)}${count ? `<span class="count">${T('small', count, 2)}</span>` : ''}</h1>`;
const h2 = (text) => `<h2>${T('h2', text, 3)}</h2>`;
const p = (text, cls = '') => `<p class="${cls}">${T(cls === 'small' ? 'small' : 'body', text)}</p>`;
const small = (text) => p(text, 'small');
const link = (text, extra = '') => `<span class="a ul ${extra}">${T('body', text, 3)}</span>`;
const lab = (text) => T('label', text, 3);

// A button. opts: primary, dis, focus, block, q (outlined, inside a plate).
function btn(text, o = {}) {
  const c = ['btn', o.primary && 'primary', o.dis && 'dis', o.focus && 'focus', o.block && 'full', o.q && 'q'].filter(Boolean).join(' ');
  return `<span class="${c}" role="button"${o.dis ? ' aria-disabled="true"' : ''}>${T('btn', text, 2)}</span>`;
}
const btns = (...list) => `<div class="btns">${list.join('')}</div>`;

// A text field. o: value, ph (placeholder), hint, error, focus, code.
function field(label, o = {}) {
  const inner = o.value ? T(o.code ? 'code' : 'body', o.value, 2) : `<span class="ph">${T('body', o.ph || '', 2)}</span>`;
  return `<div class="field${o.error ? ' err' : ''}"><span class="lab">${T('flab', label, 2)}</span>`
    + `<div class="input${o.focus ? ' focus' : ''}${o.code ? ' code' : ''}">${inner}</div>`
    + (o.hint ? `<span class="hint">${T('small', o.hint, 3)}</span>` : '')
    + (o.error ? `<div class="error" role="alert"><span class="mark away"></span>${T('small', o.error, 3)}</div>` : '') + '</div>';
}

// A plate: white, black text, for a state that needs the person. A note: outlined, for "done".
const plate = (head, detail, buttons = '') => `<div class="plate" role="alert"><div class="head2"><span class="mark away"></span>${T('title', head, 3)}</div>${detail ? `<p class="dt">${T('body', detail)}</p>` : ''}${buttons ? `<div class="btns">${buttons}</div>` : ''}</div>`;
const note = (head, detail = '') => `<div class="note" role="status"><div class="head2"><span class="mark ok"></span>${T('title', head, 3)}</div>${detail ? `<p class="dt">${T('small', detail)}</p>` : ''}</div>`;
const status = (text, kind = 'work') => `<div class="status" role="status"><span class="mark ${kind}"></span>${T('body', text, 3)}</div>`;

// The page frame. nav: 'classes' | 'devices' | 'account' | null (signed out).
function frame({ title, nav, body, narrow, comment }) {
  const link2 = (key, text) => `<span class="a${nav === key ? ' cur' : ''}"${nav === key ? ' aria-current="page"' : ''}>${T('btn', text, 1)}</span>`;
  const navHtml = nav === null ? '' : `<nav class="nav" aria-label="Main">${link2('classes', 'Classes')}${link2('devices', 'Devices')}${link2('account', 'Account')}<span class="navbtn out ul" role="button">${T('body', 'Sign out', 1)}</span></nav>`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="site.css">
</head>
<body>
<!-- ${comment}  Spec: docs/design/site.md. Generated by site-pages.js: edit that, not this file. -->
<header class="head"><div class="bar"><span class="brand">${T('brand', 'Class player', 1)}</span>${navHtml}</div></header>
<main class="page${narrow ? ' narrow' : ''}">
${body}
</main>
</body>
</html>
`;
}

// The account area: sub-navigation beside (desktop) or above (phone, tablet) the content.
function account(cur, body) {
  const items = [['sessions', 'Sessions'], ['passkeys', 'Passkeys'], ['links', 'Linked apps'], ['data', 'Your data']];
  const sub = items.map(([k, t]) => `<span class="a${cur === k ? ' cur' : ''}"${cur === k ? ' aria-current="page"' : ''}>${T('btn', t, 1)}</span>`).join('');
  return `${h1('Account')}<div class="acct"><nav class="subnav" aria-label="Account">${sub}</nav><div>${body}</div></div>`;
}

module.exports = { esc, T, h1, h2, p, small, link, lab, btn, btns, field, plate, note, status, frame, account };
