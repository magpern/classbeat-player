// Building blocks of the rider page mock-ups (docs/design/rider.md). Pure string functions, no
// I/O. Built on the companion's kit: the same gel, chips and keys, so the two phone pages read as
// one family. Every piece of text is a leaf with data-tier, so measure.js checks it.
'use strict';

const { esc, T, digits, gel, coming, key } = require('./companion-kit');

// The top line: the rider's own nickname on the left (grey, with the live dot), or a white plate
// when the page is not live; class time left on the right.
function top(text, kind = '', time = '', timeLabel = 'left') {
  const t = time ? `<span class="ct"><span class="val" data-tier="minor">${digits(time)}</span>${T('label', timeLabel)}</span>` : '';
  const body = kind === 'alert'
    ? `<span class="link alert" data-tier="label" data-lines="2">${esc(text)}</span>`
    : `<span class="link"><span class="who-t" data-tier="label" data-clamp="1">${esc(text)}</span></span>`;
  return `<header class="top">${body}${t}</header>`;
}

// The clock: time left in the interval, and the position word beside it (under it in
// landscape). o.label, o.est (not live), o.pill ("Paused").
function clock(time, position, o = {}) {
  const pill = o.pill ? `<span class="pill" data-tier="label">${esc(o.pill)}</span>` : '';
  const pos = position
    ? `<div class="song">${T('label', 'Position', 1, ' class="lbl"')}<span class="when n" data-tier="value">${esc(position)}</span></div>` : '';
  return `<section class="clock"><div class="cl"><span class="lbl">${pill}${T('label', o.label || 'Interval left')}</span>`
    + `<div class="count n${o.est ? ' est' : ''}" data-tier="hero">${digits(time)}</div></div>${pos}</section>`;
}

// The effort for the zone, worked out on the phone (rider.md, "The effort"). rows: [label, value,
// unit]. hint: a line under the rows. The values are text in white: never a zone colour (rule 7).
function effort(rows, hint = '') {
  const r = rows.map(([label, value, unit]) => `${T('label', label, 1, ' class="lbl"')}<div class="ev"><span class="n" data-tier="value">${esc(value)}</span>`
    + (unit ? `<span class="u" data-tier="minor">${esc(unit)}</span>` : '') + '</div>').join('');
  return `<section class="effort">${r}${hint ? T('label', hint, 3, ' class="hint"') : ''}</section>`;
}

const run = (inner, cls = '') => `<main class="run rider${cls ? ' ' + cls : ''}">${inner}</main>`;
const myKey = () => `<nav class="keys" aria-label="Your numbers">${key('my_numbers', 'My numbers', { full: true })}</nav>`;

// A page without the class (entry, joining, ending). form: the page may scroll vertically.
const page = (lead, act, cls = '') => `<main class="page${cls ? ' ' + cls : ''}"><div class="lead">${lead}</div><div class="act">${act}</div></main>`;
const h1 = (t, lines = 2) => `<h1>${T('value', t, lines)}</h1>`;
const p = (t, small = false, lines = 6) => `<p${small ? ' class="small"' : ''}>${T(small ? 'label' : 'minor', t, lines)}</p>`;

// A field. o: value, ph, focus, error, dim (locked while joining), unit.
const field = (label, o = {}) => `<div class="field${o.error ? ' err' : ''}${o.dim ? ' dim' : ''}">${T('label', label, 2, ' class="lab"')}<div class="input${o.focus ? ' focus' : ''}">`
  + (o.value ? T('value', o.value, 1, ' data-clamp="1"') : `<span class="ph">${T('label', o.ph || '', 1)}</span>`) + '</div>'
  + (o.error ? `<div class="err-line" role="alert">${T('label', o.error, 4)}</div>` : '') + '</div>';

// The "Remember on this phone" switch: a key, its state in words ("On" or "Off"), never colour alone.
const remember = (on, dim = false) => `<button class="key sw${on ? ' on' : ''}${dim ? ' dis' : ''}" data-action="remember" role="switch" aria-checked="${on}">`
  + `<span class="kl" data-tier="minor" data-lines="2">Remember on this phone</span><span class="st" data-tier="minor">${on ? 'On' : 'Off'}</span></button>`;

const plate = (h, dt) => `<div class="plate" role="alert">${T('minor', h, 2, ' class="h"')}${dt ? T('label', dt, 4, ' class="dt"') : ''}</div>`;

function doc(title, comment, body) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(title)}</title>
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="companion.css">
<link rel="stylesheet" href="rider.css">
</head>
<body>
<!-- ${comment}  Spec: docs/design/rider.md. Generated by rider-pages.js: edit that, not this file. -->
${body}
</body>
</html>
`;
}

module.exports = { esc, T, digits, gel, coming, key, top, clock, effort, run, myKey, page, h1, p, field, remember, plate, doc };
