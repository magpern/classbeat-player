// The update notice and the "Updates" settings (docs/design/updates.md, ADR 0014).
// `node updates-pages.js` writes updates-<state>.html (the settings page) and
// updates-list-<state>.html (the class list with the notice, or without it) beside this file.
// The list pages are class-list-synced / -long-list / -pinned-newer with the header, the notice
// and the class gate applied. All names and numbers are made up.
'use strict';
const fs = require('fs');
const path = require('path');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const M = (cap, text, extra = '') => `<span data-tier="minor" data-min-cap="${cap}"${extra}>${esc(text)}</span>`;
const L = (text) => `<span data-tier="label" data-min-cap="9.5" class="lbl">${esc(text)}</span>`;
const KBD = (k) => ` <span data-tier="label" data-min-cap="9.5" class="kbd">${k}</span>`;
const BTN = (text, k, cls = '', attr = '') => `<button${cls ? ` class="${cls}"` : ''}${attr}>${M(12, text)}${k ? KBD(k) : ''}</button>`;
const TAG = (t) => `<span class="tag" data-tier="label" data-min-cap="9.5">${esc(t)}</span>`;

// ---------- The class list with the notice ----------
const HEAD_BTN = '<button><span data-tier="minor" data-min-cap="12">Open a class file…</span> <span data-tier="label" data-min-cap="9.5" class="kbd">Ctrl+O</span></button>';
const WITH_SETTINGS = `<span style="display:flex;gap:12px">${BTN('Settings', 'Ctrl+,')}${HEAD_BTN}</span>`;
const notice = (version, pre) => `<div class="notice" role="status"><div class="what"><span class="mark news" aria-hidden="true"></span><div><div class="l1">${M(14, 'Newer version available', ' class="st"')}${M(18, version, ' class="ver n"')}${pre ? TAG('Pre-release') : ''}</div><div>${M(11, 'You have 0.1.0. Nothing is downloaded or installed.', ' data-lines="2" class="dt"')}</div></div></div>${BTN('Open release page', '', 'primary')}</div>`;
const NEEDLE = /(<\/div><\/div><\/div>)(<div class="(?:filter|cols)")/;
const listPage = (src, { settings, note, comment, title }) => {
  let h = fs.readFileSync(path.join(__dirname, src), 'utf8');
  if (settings) {
    if (!h.includes(HEAD_BTN)) throw new Error(`${src}: header button not found`);
    h = h.replace(HEAD_BTN, WITH_SETTINGS);
  }
  if (note) {
    if (!NEEDLE.test(h)) throw new Error(`${src}: status line not found`);
    h = h.replace(NEEDLE, `$1${note}$2`);
  }
  h = h.replace('<link rel="stylesheet" href="class-list.css">', '<link rel="stylesheet" href="class-list.css">\n<link rel="stylesheet" href="updates.css">');
  h = h.replace(/<!-- State:[\s\S]*?-->/, `<!-- ${comment} Spec: docs/design/updates.md. Generated by updates-pages.js from ${src}. -->`);
  return h.replace(/<title>[^<]*<\/title>/, `<title>${esc(title)}</title>`);
};

// ---------- The settings page ----------
function sw(name, help, on, focus) {
  return `<div class="sw${on ? ' on' : ''}${focus ? ' focus' : ''}" role="switch" aria-checked="${on}" tabindex="0"><div><div>${M(14, name, ' class="nm"')}</div><div>${M(11, help, ' data-lines="2" class="hp"')}</div></div><div class="ctl">${M(12, on ? 'On' : 'Off', ' class="state"')}<span class="track" aria-hidden="true"><i></i></span></div></div>`;
}
const SW_AUTO = (on, focus) => sw('Check automatically', on ? 'At start and every 6 hours while the player is open.' : 'Off: the player looks for a newer version only when you press Check now.', on, focus);
const SW_PRE = (on) => sw('Pre-releases', 'Also tell me about test versions, which come before a normal release.', on, false);
const HEAD = `<header class="head">
  <div class="title"><h1 data-tier="minor" data-min-cap="28">Settings</h1></div>
  ${BTN('Back to the classes', 'Esc')}
</header>`;
const fact = (label, value, pre) => `${L(label)}<span class="v n${value === 'Not known' ? ' none' : ''}">${value === 'Not known' ? M(14, value) : M(18, value)}${pre ? TAG('Pre-release') : ''}</span>`;
const statusRow = (mark, word, detail, btn) => `<div class="s-status" role="status"><div class="what"><span class="mark ${mark}" aria-hidden="true"></span><div>${M(14, word, ' class="st"')}<div>${M(11, detail, ' data-lines="2" class="dt"')}</div></div></div>${btn || ''}</div>`;
const CHECK = BTN('Check now');
const CHECK_BUSY = BTN('Check now', '', '', ' aria-disabled="true"');
const OPEN = BTN('Open release page', '', 'primary');
const page = ({ status, current = '0.1.0', latest, latestPre, auto = true, pre = false, check = CHECK, focus = 'check' }) => `${HEAD}
<main class="settings"><h2 data-tier="minor" data-min-cap="22">Updates</h2>
${status}
<div class="facts">${fact('Current version', current)}${fact('Latest version', latest, latestPre)}</div>
<div class="actions">${check}</div>
<div class="switches">${SW_AUTO(auto, focus === 'auto')}${SW_PRE(pre)}</div></main>`;

const pages = {};
const add = (name, title, comment, body) => { pages[name] = { title, comment, body }; };
add('up-to-date', 'Settings: up to date',
  'State: "Up to date". Filled circle. The latest version equals the current one. No "Open release page" (absent, not disabled). Both switches at their defaults: Check automatically on, Pre-releases off. Initial focus on Check now.',
  page({ status: statusRow('ok', 'Up to date', 'You have the newest version.'), latest: '0.1.0' }));
add('newer', 'Settings: newer version available',
  'State: "Newer version available". Filled square. "Open release page" is the primary button, first stop after Back. Check now stays. Initial focus on Open release page.',
  page({ status: statusRow('news', 'Newer version available', 'Version 0.2.0 is on its release page. Nothing is downloaded or installed.', OPEN), latest: '0.2.0' }));
add('newer-prerelease', 'Settings: newer pre-release available',
  'State: "Newer version available" with Pre-releases on and the latest a pre-release (a hyphen in the version). The version is shown as its tag has it, with the word "Pre-release" beside it.',
  page({ status: statusRow('news', 'Newer version available', 'Version 0.3.0-rc.1 is on its release page. Nothing is downloaded or installed.', OPEN), latest: '0.3.0-rc.1', latestPre: true, pre: true }));
add('checking', 'Settings: checking',
  'State: "Checking…". Hollow circle, still. Check now stays in the tab order with aria-disabled and dimmed; pressing it does nothing. A latest version already known stays shown; with none, "Not known". "Open release page" is never shown while a check is running.',
  page({ status: statusRow('work', 'Checking…', 'Looking for a newer version.'), latest: 'Not known', check: CHECK_BUSY }));
add('could-not-check', 'Settings: could not check',
  'State: "Could not check". Hollow square (a normal state, as Offline on the class list, not a plate). The player works as before. Latest version "Not known" when no check has ever succeeded.',
  page({ status: statusRow('away', 'Could not check', 'The list of releases could not be read. Press Check now to try again.'), latest: 'Not known' }));
add('before-any-check', 'Settings: before any check',
  'State: before any update check has run (automatic checks off, none pressed yet). The status is still "Could not check" with the same hollow square; only the detail line differs, saying that no check has run yet. Latest version "Not known".',
  page({ status: statusRow('away', 'Could not check', 'No check has run yet. Press Check now.'), latest: 'Not known', auto: false }));
add('auto-off', 'Settings: automatic checks off, pre-releases on',
  'State: both switches changed from their defaults, the keyboard focus on Check automatically (its focus ring). With automatic checks off the help text says when the player looks.',
  page({ status: statusRow('ok', 'Up to date', 'You have the newest version.'), latest: '0.1.0', auto: false, pre: true, focus: 'auto' }));

const LISTS = {
  'list-newer': ['class-list-synced.html', 'Class list: newer version available',
    'State: a newer stable version, no class open and no other plate. The notice sits under the sync status: the words "Newer version available", the version, and "Open release page". A "Settings" key is in the header.',
    { settings: true, note: notice('0.2.0', false) }],
  'list-newer-prerelease': ['class-list-synced.html', 'Class list: newer pre-release available',
    'State: Pre-releases on and the latest is a pre-release. The version is shown as its tag has it, with "Pre-release" beside it.',
    { settings: true, note: notice('0.3.0-rc.1', true) }],
  'list-newer-long': ['class-list-long-list.html', 'Class list: newer version with the filter shown',
    'State: the worst case for height: 42 classes (the filter is shown) and the notice. At 1000x720 at least five rows are whole.',
    { settings: true, note: notice('0.2.0', false) }],
  'list-up-to-date': ['class-list-synced.html', 'Class list: no newer version',
    'State: up to date, could not check, checking and every other result show nothing on the list. Only the Settings key is new; the list is as in class-list.md.',
    { settings: true }],
  'list-class-playing': ['class-list-pinned-newer.html', 'Class list: a class is playing (the gate)',
    'State: the class gate. A class is pinned. A newer version may be known but is held: no notice and no Settings key (absent, not disabled). They return when the instructor is on the list with no class pinned.',
    {}],
};
const NAMES = Object.keys(pages);
const LIST_NAMES = Object.keys(LISTS);

const doc = (name) => {
  const { title, comment, body } = pages[name];
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>${esc(title)}</title>
<link rel="stylesheet" href="tokens.css">
<link rel="stylesheet" href="class-list.css">
<link rel="stylesheet" href="updates.css">
</head>
<body>
<!-- ${comment} Spec: docs/design/updates.md. Generated by updates-pages.js. -->
<div class="app">
${body}
</div>
</body>
</html>
`;
};
const listDoc = (name) => {
  const [src, title, comment, opt] = LISTS[name];
  return listPage(src, { ...opt, comment, title });
};

if (require.main === module) {
  for (const n of NAMES) fs.writeFileSync(path.join(__dirname, `updates-${n}.html`), doc(n));
  for (const n of LIST_NAMES) fs.writeFileSync(path.join(__dirname, `updates-${n}.html`), listDoc(n));
  console.log(`${NAMES.length + LIST_NAMES.length} mock-ups written`);
}
module.exports = { NAMES, LIST_NAMES };
